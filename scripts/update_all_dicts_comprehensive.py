for lang_code, (base_dict, filename) in [
    ('en', (DICT_EN, 'dict_en.py')),
    ('rw', (DICT_RW, 'dict_rw.py')),
    ('fr', (DICT_FR, 'dict_fr.py')),
    ('sw', (DICT_SW, 'dict_sw.py')),
    ('ko', (DICT_KO, 'dict_ko.py')),
    ('zh', (DICT_ZH, 'dict_zh.py')),
]:
    data = COMPREHENSIVE_ADDITIONS['en'] if lang_code == 'en' else LANG_TRANSLATIONS[lang_code]
    for section_name, section_keys in data.items():
        if section_name not in base_dict:
            base_dict[section_name] = {}
        base_dict[section_name].update(section_keys)
    
    # Save back to file
    dict_var = f'DICT_{lang_code.upper()}'
    filepath = os.path.join(os.path.dirname(__file__), 'i18n_data', filename)
    with open(filepath, 'w', encoding='utf-8') as f:
        f.write(f'# {filename}\n')
        f.write(f'{dict_var} = ')
        pprint.pprint(base_dict, stream=f, indent=2, width=120, sort_dicts=True)
        f.write('\n')
    print(f'Successfully updated {filename}')

